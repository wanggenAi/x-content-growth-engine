"""Machine-readable editorial gate; this validates readiness, never predicts reach."""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from .ai_flavor_gate import ai_flavor_passes
from .human_voice import (
    HUMAN_STYLE_ENGINE_VERSION,
    HUMAN_STYLE_GENERATOR,
    HUMAN_STYLE_VERSION,
    run_human_style_pipeline,
    stable_hash,
)
from .reader_model import profile_errors, reader_model_semantic_integrity, review_profile

PRIMARY_ACTIONS = {
    "SHARE", "REPLY", "QUOTE", "FOLLOW", "DWELL", "SAVE_RETURN", "CLICK_RESOURCE", "LIKE"
}
EDITORIAL_STATES = {
    "DISCOVERED", "SOURCE_CHECKED", "MATERIAL_STRONG", "DRAFT", "EDITORIAL_REVIEW",
    "READY_FOR_MANUAL_PUBLISH", "PUBLISHED_PENDING_FEEDBACK", "OBSERVATION_CLOSED",
    "LEARNING_REVIEWED", "FAIL_LOW_INTEREST", "FAIL_REPETITIVE", "FAIL_NO_PAYLOAD",
    "FAIL_NO_PRIMARY_ACTION", "HOLD_NEEDS_EVIDENCE", "RESEARCH_ONLY",
}
REQUIRED_FIELDS = (
    "candidate_id", "research_version", "publication_version", "subject_value",
    "payload", "primary_action", "novelty_check", "audit_language_separation", "material_strength",
    "source_refs", "fact_check_status", "human_checked",
    "reader_model",
)

@dataclass(frozen=True)
class GateResult:
    ready: bool
    reasons: tuple[str, ...]
    state: str


def _text(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def _human_voice_errors(candidate: dict[str, Any]) -> list[str]:
    """Validate a code-generated, hash-bound Human Style contract."""
    contract = candidate.get("human_style")
    if not isinstance(contract, dict):
        return ["human_style contract is required before manual publication"]
    errors: list[str] = []
    if contract.get("version") != HUMAN_STYLE_VERSION:
        errors.append("human_style version must be HUMAN_STYLE_V2")
    if not isinstance(candidate.get("draft_text_before_human_style"), str):
        errors.append("draft_text_before_human_style is required for input hash verification")
    elif contract.get("input_text_hash") != stable_hash(candidate["draft_text_before_human_style"]):
        errors.append("human_style input_text_hash does not match the generated draft")
    if contract.get("output_text_hash") != stable_hash(candidate.get("text", "")):
        errors.append("human_style output_text_hash does not match candidate.text")
    if contract.get("locked_facts_hash") != stable_hash(candidate.get("locked_facts", {})):
        errors.append("human_style locked_facts_hash does not match candidate.locked_facts")
    if contract.get("generated_by") != HUMAN_STYLE_GENERATOR:
        errors.append("human_style contract must be generated by candidate_pipeline")
    if contract.get("engine_version") != HUMAN_STYLE_ENGINE_VERSION:
        errors.append("human_style engine_version is invalid")
    for field in ("ai_flavor_score_before", "ai_flavor_score_after"):
        if not isinstance(contract.get(field), (int, float)):
            errors.append(f"human_style.{field} is required")
    score = contract.get("ai_flavor_score_after")
    if isinstance(score, (int, float)) and not ai_flavor_passes({"score": score, "blocked": False}):
        errors.append("AI flavor gate is blocked or above threshold")
    if contract.get("x_native_style") != "PASS":
        errors.append("X native style gate must be PASS")
    if contract.get("fact_preservation") != "PASS":
        errors.append("fact preservation gate must be PASS")
    action = candidate.get("primary_action")
    comment_status = contract.get("comment_impulse")
    if action == "REPLY" and comment_status != "PASS":
        errors.append("REPLY requires a passing comment impulse gate")
    if action != "REPLY" and comment_status not in {"PASS", "NOT_APPLICABLE"}:
        errors.append("non-REPLY comment impulse status is invalid")
    # Re-run the deterministic engine so a caller cannot manufacture a PASS
    # contract by copying hashes while changing scores, statuses, or audit
    # operations.  The timestamp is intentionally excluded from this check.
    if not errors:
        expected = run_human_style_pipeline({
            "draft_text": candidate["draft_text_before_human_style"],
            "locked_facts": candidate.get("locked_facts", {}),
            "target_platform": candidate.get("target_platform", "X_ZH"),
            "voice_profile": candidate.get("voice_profile", "GEN_DEFAULT"),
            "primary_action": candidate.get("primary_action"),
            "source_context": candidate.get("source_context", []),
            "preserve_quotes": candidate.get("preserve_quotes", True),
        })
        expected_contract = dict(expected["human_style"])
        expected_contract["generated_by"] = HUMAN_STYLE_GENERATOR
        for field, expected_value in expected_contract.items():
            if field == "evaluated_at":
                continue
            if contract.get(field) != expected_value:
                errors.append(f"human_style.{field} does not match deterministic engine output")
        if candidate.get("text") != expected["rewritten_text"]:
            errors.append("candidate.text does not match deterministic Human Style output")
        if contract.get("operations") != expected.get("operations"):
            errors.append("human_style.operations do not match deterministic engine output")
    return errors


def validate_candidate(candidate: dict[str, Any]) -> GateResult:
    """Validate a candidate record without changing its state or inventing evidence."""
    reasons: list[str] = []
    state = candidate.get("state", "EDITORIAL_REVIEW")
    missing = [key for key in REQUIRED_FIELDS if key not in candidate]
    if missing:
        reasons.append("missing fields: " + ", ".join(missing))
    for key in REQUIRED_FIELDS:
        if key in {"source_refs", "human_checked", "reader_model"}:
            continue
        if key in candidate and not _text(candidate[key]):
            reasons.append(f"{key} must be a concrete non-empty statement")
    if not isinstance(candidate.get("source_refs"), list) or not candidate.get("source_refs"):
        reasons.append("source_refs must be a non-empty list")
    action = candidate.get("primary_action")
    if not isinstance(action, str) or action not in PRIMARY_ACTIONS:
        reasons.append("primary_action must be exactly one allowed action")
    if candidate.get("material_strength") != "STRONG":
        reasons.append("material_strength must be STRONG")
    human_review_waived = (
        candidate.get("human_checked") is not True
        and candidate.get("agent_checked") is True
        and candidate.get("user_authorized") is True
        and candidate.get("publication_review_exception") == "USER_AUTHORIZED_AGENT_REVIEW"
    )
    if candidate.get("human_checked") is not True and not human_review_waived:
        reasons.append("human_checked must be true before manual publication review")
    if candidate.get("fact_check_status") in {"UNVERIFIED", "UNKNOWN", None}:
        reasons.append("fact_check_status must describe checked boundaries")
    if state not in EDITORIAL_STATES:
        reasons.append(f"invalid editorial state: {state}")
    if state in {"FAIL_LOW_INTEREST", "FAIL_REPETITIVE", "FAIL_NO_PAYLOAD", "FAIL_NO_PRIMARY_ACTION", "HOLD_NEEDS_EVIDENCE", "RESEARCH_ONLY"}:
        reasons.append(f"editorial hold/failure state cannot pass: {state}")
    # Historical published records predate HUMAN_VOICE_V1 and remain auditable.
    # Any record seeking a new manual publication slot must carry the contract.
    if state == "READY_FOR_MANUAL_PUBLISH":
        reasons.extend(_human_voice_errors(candidate))
        from .viral_admission import candidate_admission
        expected_admission = candidate_admission(candidate)
        if candidate.get("viral_admission") != expected_admission:
            reasons.append("VIRAL_ADMISSION_GATE: stale or forged admission contract")
        reasons.extend(expected_admission["reasons"])
    profile = candidate.get("reader_model")
    # Published historical V1 records remain readable for audit and feedback.
    # New admissions still require the explicit V2 route/action contract.
    historical_legacy = (isinstance(profile, dict) and profile.get("model_version") == "SELF_MIRRORING_V1" and
                         state in {"PUBLISHED_PENDING_FEEDBACK", "OBSERVATION_CLOSED", "LEARNING_REVIEWED"})
    model_errors = profile_errors(profile, for_candidate=not historical_legacy, primary_action=action if isinstance(action, str) else None)
    reasons.extend(model_errors)
    # New candidates with text must carry a profile grounded in that text.  Do
    # not rewrite or migrate historical published annotations in place.
    if state not in {"PUBLISHED_PENDING_FEEDBACK", "OBSERVATION_CLOSED", "LEARNING_REVIEWED"} and isinstance(candidate.get("text"), str) and candidate.get("text").strip():
        semantic = reader_model_semantic_integrity(candidate)
        reasons.extend(semantic["reasons"])
    if not model_errors and not historical_legacy:
        review = review_profile(profile, action)
        reasons.extend(review["reasons"])
        if profile["material_strength"] != "HIGH":
            reasons.append("reader_model material strength must be HIGH")
        if profile["novelty_status"] != "CHECKED":
            reasons.append("reader_model novelty review must be CHECKED")
    if state == "READY_FOR_MANUAL_PUBLISH" and reasons:
        reasons.append("READY_FOR_MANUAL_PUBLISH is not allowed while gate reasons remain")
    return GateResult(not reasons, tuple(reasons), state if state in EDITORIAL_STATES else "EDITORIAL_REVIEW")
